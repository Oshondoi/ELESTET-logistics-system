## 1. Превращение заявки в партию

Да, именно так:

```text
Заявка:
Заявлено 500 единиц
Коробов ориентировочно 12
Комментарий клиента
Предварительный список товаров

                ↓ Начать фактическую приёмку

Партия:
Заявлено: 500
Принято: 487
Брак: 4
Недостача: 13
Излишек: 4
Фактические короба: 11
```

Технически это не смена `type` одной строки. Выполняется одна атомарная операция:

```text
convert_request_to_batch(request_id, store_id, pipeline_id, reception_context)
```

Она:

1. Проверяет права.
2. Проверяет получателя заявки.
3. Требует выбрать или создать магазин.
4. Создаёт партию.
5. Создаёт строки `Заявлено` из последней подтверждённой версии заявки.
6. Связывает заявку с партией.
7. Переводит заявку в `converted`.
8. Открывает этап фактической приёмки.
9. Записывает событие истории.
10. Уведомляет клиента.

Связь остаётся навсегда:

```text
request.source_snapshot
request.converted_batch_id
batch.source_request_id
```

Если после преобразования клиент изменит заявку, данные партии автоматически меняться не должны. Иначе уже начатая приёмка внезапно получит другое «Заявлено». Изменение оформляется новой версией и отдельно принимается исполнителем.

## 2. Передача готовых партий между компаниями

Здесь нельзя выбирать только между «заявкой» и нынешним «аутсорсом». Это два разных сценария, и оба нужны.

### Сценарий A: аутсорс отдельного этапа

Компания A остаётся владельцем партии. Компания B выполняет отдельный этап:

```text
Компания A владеет партией
├─ Приёмка — Компания A
├─ ОТК — Компания B
├─ Упаковка — Компания B
└─ Логистика — Компания A
```

Это существующая модель pipeline/outsource. Новая партия у B не создаётся. B видит только разрешённые данные и работает только на назначенном этапе.

Использовать, когда A продолжает управлять всей партией.

### Сценарий B: передача готовой партии как новой работы другой компании

Компания A передаёт данные партии компании B как заявку:

```text
Партия A
   ↓ «Передать компании C-52»
Заявка в компании B
   ↓ B принимает и начинает работу
Партия B
```

Здесь:

- партия A остаётся собственностью A;
- B получает заявку со снимком переданных данных;
- B не получает права редактировать исходную партию A;
- после принятия B создаёт свою партию;
- две партии связываются отношением передачи.

```text
request.source_batch_id = партия A
request.target_batch_id = партия B
request.sender_account_id = A
request.recipient_account_id = B
```

Это правильнее, чем давать одной партии двух владельцев. Одна партия всегда принадлежит одной компании.

### Как их объединить в интерфейсе

У партии A могут быть две разные команды:

- `Передать этап партнёру` — текущий аутсорс;
- `Передать партию компании` — создаёт входящую заявку у другой компании.

Так пользователь не смешивает выполнение этапа с полной передачей работы.

## 3. Единая сущность заявки

Лучше назвать таблицу не только `intake_requests`, а шире — например `service_requests`, потому что она будет принимать разные источники:

```text
request_kind:
- simple_intake       простая заявка
- detailed_intake     детальная заявка
- batch_handoff       передача готовой партии
```

При этом все три вида используют общий жизненный цикл и один список входящих заявок.

Заявка должна иметь:

```text
sender_account_id        nullable — незарегистрированный клиент
sender_user_id           nullable
recipient_account_id     обязательный после отправки
client_relationship_id
source_batch_id          только для batch_handoff
converted_batch_id
store_id                 nullable до преобразования
request_kind
status
current_revision
created_by_actor
```

## 4. Адресация по ID компании

Идея с неизменяемым `C-` правильная.

Поле выглядит так:

```text
Компания-получатель
C- [  52  ]
```

Пользователь вводит только число. После проверки сервер показывает:

```text
C-52 · Ак Логистик
```

И требует подтверждение перед отправкой.

Заявка должна адресоваться не сотруднику, а компании:

```text
recipient_account_id
```

Уже внутри компании она может быть назначена сотруднику:

```text
assigned_user_id
```

Нужна защита от спама:

- компания может запретить новые заявки;
- заблокировать конкретного отправителя;
- принимать только заявки от подтверждённых партнёров;
- ограничить частоту отправки;
- при необходимости сменить публичный код приёма, не меняя `C-ID`.

Сам `C-ID` менять нельзя: это постоянный короткий ID компании.

## 5. Ссылки: короткая и безопасная структура

Предыдущая вложенная ссылка `/portal/CL-7/R-184` действительно визуально перегружена.

Предлагаю три коротких маршрута:

```text
elestet.net/c/K7M4Q2   — постоянный клиентский кабинет
elestet.net/r/N8D4W6   — конкретная заявка
elestet.net/i/...      — одноразовое приглашение
```

Где `K7M4Q2` и `N8D4W6` — случайные публичные коды, а не последовательные ID.

При этом внутри интерфейса показываются нормальные ID:

```text
Клиент CL-7
Заявка R-184
Компания C-52
Партия P-381
```

Правила:

- короткий код помогает найти объект, но не является паролем;
- одна сессия клиента открывает все его разрешённые заявки;
- `/r/N8D4W6` после входа сразу открывает нужную заявку;
- длинный секретный токен используется только при первом приглашении или сбросе;
- после принятия приглашения токен аннулируется.

Для зарегистрированной компании отдельная постоянная клиентская ссылка необязательна. Она входит в ELESTET и видит `Исходящие заявки`. Но короткая ссылка конкретной заявки всё равно полезна для пересылки сотрудникам.

## 6. Один пароль и все заявки клиента

Согласен: один клиентский доступ, один пароль, все его заявки.

Правильная связь:

```text
Клиентская карточка у исполнителя
        ↓
Доступ клиента к порталу
        ↓
Все заявки этой клиентской карточки
```

Но пароль относится не к ссылке и не к заявке, а к клиентскому пользователю или гостевому клиентскому доступу.

### Незарегистрированный клиент

Исполнитель создаёт:

- клиентскую карточку;
- основной контакт;
- доступ в клиентский кабинет;
- приглашение установить пароль.

После входа клиент видит все заявки, связанные с этой карточкой.

### Зарегистрированный клиент

Доступ определяется его аккаунтом ELESTET. Пароль обычный — от его пользователя. Он видит:

- свои исходящие заявки;
- связанные партии;
- документы;
- статусы;
- входящие запросы, если сам является исполнителем.

### Кто сбрасывает пароль

Сам клиент:

- через подтверждённый email;
- позднее через телефон/OTP.

Уполномоченный сотрудник исполнителя:

- не видит пароль;
- отправляет ссылку сброса;
- аннулирует активные сессии;
- создаёт новое одноразовое приглашение;
- временно блокирует доступ.

Право:

```text
client_portal_access_manage
```

Обычный исполнитель этапа этого делать не может.

## 7. Нужно ли сотруднику открывать клиентскую ссылку

Нет. Сотруднику не нужно входить через ссылку клиента.

Он видит заявку в своём рабочем интерфейсе по обычным правам:

```text
request_view
request_manage
request_assign
request_convert
client_portal_access_manage
```

Рекомендую:

- `request_view` — просмотр входящих заявок;
- `request_manage` — уточнение, принятие, отклонение;
- `request_assign` — назначение ответственного;
- `request_convert` — преобразование в партию;
- `client_manage` — связь клиента с магазинами;
- `client_portal_access_manage` — управление доступом;
- `request_history_view` — просмотр полного аудита.

Кнопку `Посмотреть как клиент` лучше не делать на первом этапе. Она создаёт риск путаницы и утечки. Вместо неё можно сделать безопасный `Предпросмотр клиентского окна`, без возможности выполнять клиентские действия.

## 8. Клиент, компания и магазин — двойная связь

Тут действительно нужны две связи, но нельзя хранить клиента как «роль магазина».

Правильная структура:

```text
Компания-исполнитель
 └─ Клиентская карточка
     ├─ гостевой клиент или связанная компания ELESTET
     ├─ контакты
     ├─ доступ к порталу
     └─ один или несколько магазинов WB
```

Например:

```text
client_relationships
- provider_account_id
- client_account_id nullable
- display_name
- status
- portal_public_code
```

```text
client_store_links
- client_relationship_id
- store_id
- is_default
```

Почему отдельная клиентская карточка нужна даже зарегистрированному клиенту:

- у него может быть несколько магазинов;
- исполнитель может хранить собственное рабочее название;
- нужны контакты, договорные условия и история отношений;
- клиент может позже зарегистрироваться;
- одна компания может быть клиентом нескольких исполнителей;
- клиент может одновременно быть партнёром по аутсорсу.

Магазин остаётся магазином WB. Клиентская карточка остаётся отношением между заказчиком и исполнителем.

## 9. Как легко привязать заявку к магазину

В карточке заявки нужен блок:

```text
Клиент:
Ак Логистик
Компания ELESTET:
C-52
Магазин:
Не привязан
```

Кнопки:

- `Выбрать существующий магазин`;
- `Создать магазин`;
- `Связать магазин клиента`;
- `Назначить по умолчанию`.

После первой успешной связи система запоминает её в `client_store_links`. В следующей заявке этого клиента предлагает магазин автоматически, но сотрудник подтверждает выбор.

Ссылку клиента можно хранить рядом с клиентской карточкой, но не в поле самого магазина. У клиента может быть несколько магазинов, а один портал должен показывать их все.

В магазине допустимо показывать:

```text
Клиент: Ак Логистик
Клиентский кабинет: Открыть
```

Но источником связи остаётся `client_relationships`, а не строковое поле URL.

## 10. Простая и детальная формы заявки

Нужны три способа создания:

### Простая заявка

Для клиента, который не хочет заполнять номенклатуру:

Обязательно:

- компания-получатель `C-ID`;
- количество;
- единица количества;
- способ передачи товара;
- контакт, если клиент не авторизован.

Единица количества обязательна, иначе `500` невозможно правильно понять:

```text
500 штук
12 коробов
3 паллеты
8 мешков
```

Рекомендую обязательное поле:

```text
Что передаёте:
- товар поштучно;
- короба;
- паллеты;
- смешанный груз.
```

Необязательно:

- магазин;
- адрес забора;
- желаемая дата;
- комментарий;
- фотографии;
- предварительное число коробов;
- список товаров;
- документы.

### Детальная заявка

Дополнительно:

- товарные баркоды;
- размеры;
- артикулы;
- количество по позициям;
- КИЗ;
- предполагаемые короба;
- вес и габариты;
- дополнительные услуги.

### Из готовой партии

Данные заполняются снимком существующей партии:

- товары;
- заявленное количество;
- короба;
- системные ШК;
- магазин;
- документы;
- комментарий отправителя.

Получатель не редактирует исходную партию отправителя. Он работает с полученной заявкой и собственной партией.

## 11. Зачем клиенту заполнять данные

Твоя логика рабочая, но формулировать клиенту лучше не через угрозу «товар потеряется».

Понятное сообщение:

> Укажите данные клиента и магазина, чтобы система однозначно связала товар, заявку, короба, документы и уведомления. Без этой связи начать фактическую приёмку невозможно.

Минимальные данные до начала приёмки:

- клиентская карточка;
- получатель;
- магазин;
- контакт;
- единица и заявленное количество;
- способ передачи товара.

Саму заявку можно отправить без магазина. Но начать фактическую приёмку и создать партию без магазина нельзя, потому что текущая модель партии и дальнейшие WB-процессы требуют точной магазинной принадлежности.

## 12. История заявки, включая гостя

Нужна append-only история:

```text
request.created
request.edited
request.submitted
request.viewed
request.assigned
request.clarification_requested
request.resubmitted
request.approved
request.rejected
request.cancelled
request.converted
```

Каждое событие хранит:

```text
actor_type
actor_user_id nullable
guest_access_id nullable
actor_account_id nullable
before_snapshot
after_snapshot
created_at
reason
```

Для незарегистрированного клиента можно достоверно сказать:

```text
Изменено через гостевой доступ клиента
