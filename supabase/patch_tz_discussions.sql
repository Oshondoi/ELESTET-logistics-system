## 18. QR оплаты и реквизиты

Твоя идея с загрузкой изображения или PDF и обрезкой хорошая.

Поток:

1. Пользователь с правом оплаты загружает PNG, JPG или PDF.
2. Для PDF система отображает нужную страницу.
3. Открывается квадратное окно кадрирования.
4. Пользователь выделяет область QR.
5. Система убирает пустые поля.
6. Выполняется пробное распознавание QR.
7. Показывается результат и предпросмотр.
8. После подтверждения сохраняются:
   - оригинал;
   - координаты обрезки;
   - подготовленное изображение;
   - распознанное содержимое QR;
   - автор и время изменения.

Настройки компании:

- показывать QR оплаты;
- показывать реквизиты;
- показывать оба;
- не показывать ничего;
- выбрать положение на документе.

Права:

```text
payment_details_view
payment_details_manage
document_template_manage
```

QR нельзя разрешать менять любому сотруднику: подмена QR может перенаправить оплату злоумышленнику.

Нужны два режима:

- `Статический QR` — загруженное изображение с постоянными реквизитами;
- `Динамический QR` — позднее создаётся под конкретный счёт и сумму.

Электронный и печатный документ должны выглядеть одинаково. Используется один PDF-шаблон.

