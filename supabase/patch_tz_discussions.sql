- дата;
- источник;
- есть расхождение;
- требуется действие.

Отдельная страница заявок сейчас не нужна. Заявка — вход в fulfillment-процесс, поэтому вкладка внутри Fulfillment логична.

Для зарегистрированного клиента:

- во своей компании он видит `Исходящие заявки`;
- у компании-получателя эта же заявка отображается как `Входящая`;
- физически это одна запись, а не две копии.

## 14. Статусы заявки

Предлагаю немного изменить список.

### `draft` — Черновик

Заявка ещё не отправлена. Её видит только автор и его компания.

Разрешено:

- редактировать;
- удалить;
- отправить.

### `submitted` — Отправлена

Заявка доставлена компании-получателю, но ещё не взята в работу.

Клиент может видеть её, но редактирование лучше выполнять через новую ревизию.

### `reviewing` — На рассмотрении

Получатель открыл заявку и назначил ответственного.

Это полезно клиенту: он понимает, что заявка не просто лежит непрочитанной.

### `needs_clarification` — Нужно уточнение

Получатель запросил данные:

- магазин;
- адрес;
- количество;
- фотографии;
- состав;
- дату.

Клиент вносит изменения и повторно отправляет. Старая версия сохраняется.

### `approved` — Согласована

Получатель готов принять работу, но фактическая приёмка ещё не началась.

На этом статусе можно согласовать дату, способ передачи и предварительные условия.

### `rejected` — Отклонена

Получатель отказался выполнять заявку. Причина обязательна.

Это финальный статус, но заявку можно скопировать в новую.

### `cancelled` — Отменена

Отмена инициирована клиентом или уполномоченным сотрудником до преобразования в партию. Источник отмены и причина фиксируются.

### `converted` — Преобразована в партию

Создана партия, заявленные данные перенесены в приёмку. Заявка становится read-only, кроме комментариев и документов, если это отдельно разрешено.

`archived` лучше не делать бизнес-статусом. Архив — представление завершённых записей, а не состояние процесса.

## 15. Единая фактическая приёмка

Согласен с твоим уточнением: отдельную обязательную «передачу при заборе» и потом вторую «складскую приёмку» вводить не нужно.

Есть одна фактическая приёмка, которая выполняется там, где компания реально решила пересчитать и зафиксировать товар:

```text
reception_context:
- pickup_site          у клиента при заборе
- own_warehouse        на складе исполнителя
- partner_warehouse    на складе партнёра
- other
```

Для Ак Логистик основной сценарий:

1. Сотрудник приезжает к клиенту.
2. Открывает заявку.
3. Если магазин ещё не связан — связывает.
4. Нажимает `Начать приёмку`.
5. Система создаёт партию.
6. Данные заявки попадают в `Заявлено`.
7. Сотрудник сканирует товары и короба.
8. Система формирует `Принято по факту`.
9. Фиксируются расхождения, фото и комментарии.
10. Клиент и сотрудник согласуют результат.
11. Формируется единый документ.
12. После этого товар едет на склад уже как принятая партия.

Если клиент сам отправил товар:

1. Заявка ожидает прибытия.
2. На складе сотрудник открывает её.
3. Нажимает `Начать приёмку`.
4. Далее выполняется тот же процесс.

Таким образом бизнес-логика одна, отличается только место.

Если выездная приёмка уже полностью завершена, на складе не нужна повторная товарная приёмка. При прибытии сканируются короба и фиксируется перемещение/сохранность:

```text
Короб прибыл на склад
Пломба/упаковка цела
Расхождений при транспортировке нет
```

Это складское перемещение, а не повтор этапа приёмки.

## 16. Подпись мышкой, пальцем или стилусом

Специальное оборудование не требуется.

В браузере открывается большое белое поле — HTML Canvas. Оно принимает:

- мышь на компьютере;
- палец на телефоне или планшете;
- стилус.

Браузер передаёт координаты движения, а приложение рисует линию. Реализуется через Pointer Events, которые объединяют мышь, touch и стилус.

Сохранять лучше:

- исходные штрихи и координаты;
- готовое PNG-изображение подписи;
- дату и время;
- пользователя или гостевой доступ;
- ревизию документа;
- hash подписанного документа;
- способ подписи.

Варианты:

1. `Подписать на экране` — подпись вставляется в PDF.
2. `Распечатать для ручной подписи` — в PDF остаётся пустой блок.
3. `Пропустить подпись` — только при наличии права и с обязательной причиной.
4. Позднее — подтверждение одноразовым кодом.

Если после подписи изменилось фактическое количество, старая подпись больше не действует. Создаётся новая ревизия документа.

Нарисованная подпись технически подтверждает согласование внутри сервиса, но не автоматически является квалифицированной электронной подписью.

