## 20. Прибытие на склад и отправка на FBO

С учётом единой фактической приёмки логика такая.

### Если товар уже принят при заборе

На складе сканируется системный QR короба:

```text
box.received_at_warehouse
```

Фиксируются:

- склад;
- зона/адрес при необходимости;
- сотрудник;
- время;
- состояние упаковки;
- повреждение;
- комментарий.

Товары внутри повторно не пересчитываются, если короб не вскрывался и нет причины для контрольной приёмки.

### Если товар не принимался при отправке

На складе из заявки запускается единая фактическая приёмка. Именно она создаёт партию, короба и фактические количества.

### Отправка на FBO

Каждый короб сканируется:

```text
box.dispatched_to_wb
```

Система проверяет:

- короб относится к нужной партии;
- связан с нужной поставкой;
- приёмка завершена;
- обязательные КИЗ и документы готовы;
- короб ещё не был отправлен;
- WB ШК привязан, если выбран WB-режим;
- системный QR не изменяется.

У поставки вычисляется агрегированный статус:

```text
0/N отправлено      → готовится
часть отправлена    → частичная отгрузка
N/N отправлено      → отгружена
```

У партии этап меняется только по утверждённым правилам pipeline, а не от одного случайного сканирования.

## 21. Итоговая структура

```text
Компания-отправитель или гость
        ↓
Клиентская карточка у получателя
        ↓
Заявка
├─ простая
├─ детальная
└─ из готовой партии
        ↓
Согласование
        ↓
Выбор/создание магазина
        ↓
Начало фактической приёмки
        ↓
Партия получателя
├─ Заявлено — снимок заявки
├─ Принято — фактический результат
├─ Расхождения
├─ Короба и QR
├─ Документ и подпись
└─ Pipeline
        ↓
Перемещения коробов
        ↓
Отправка FBO/FBS
```

Аутсорс остаётся параллельным механизмом:

```text
Передача этапа → одна партия, другой исполнитель
Передача партии → заявка и новая партия у получателя
```

