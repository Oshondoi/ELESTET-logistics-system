type GuideCardProps = {
  title: string
  items: string[]
  tone?: 'violet' | 'blue' | 'emerald' | 'amber' | 'slate'
}

const toneClasses: Record<NonNullable<GuideCardProps['tone']>, string> = {
  violet: 'border-violet-200 bg-violet-50/60',
  blue: 'border-blue-200 bg-blue-50/60',
  emerald: 'border-emerald-200 bg-emerald-50/60',
  amber: 'border-amber-200 bg-amber-50/60',
  slate: 'border-slate-200 bg-white',
}

function GuideCard({ title, items, tone = 'slate' }: GuideCardProps) {
  return (
    <article className={`rounded-2xl border p-4 ${toneClasses[tone]}`}>
      <h3 className="text-sm font-bold text-slate-900">{title}</h3>
      <ul className="mt-3 space-y-2 text-xs leading-5 text-slate-600">
        {items.map((item) => (
          <li key={item} className="flex gap-2">
            <span className="mt-[7px] h-1.5 w-1.5 shrink-0 rounded-full bg-violet-400" />
            <span>{item}</span>
          </li>
        ))}
      </ul>
    </article>
  )
}

function SectionTitle({ number, title, description }: { number: string; title: string; description?: string }) {
  return (
    <div className="mb-3 flex items-start gap-3">
      <span className="flex h-7 min-w-7 items-center justify-center rounded-lg bg-slate-900 px-2 text-xs font-bold text-white">{number}</span>
      <div>
        <h2 className="text-base font-bold text-slate-900">{title}</h2>
        {description && <p className="mt-0.5 text-xs leading-5 text-slate-500">{description}</p>}
      </div>
    </div>
  )
}

